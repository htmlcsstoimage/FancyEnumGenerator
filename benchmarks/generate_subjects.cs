// The repo's Directory.Build.props targets netstandard2.0 (for the library), which also applies to this script.
#:property TargetFramework=net10.0

// Generates FancyEnumGenerator.Benchmarks/Subjects.cs: the enums every benchmark runs against.
// Run from benchmarks/:  dotnet run generate_subjects.cs
// (It lives here, outside the benchmark project, so the project's **/*.cs glob doesn't compile it.)

string[] adjectives = ["Amber", "Bright", "Crimson", "Distant", "Early", "Frozen", "Golden", "Hidden", "Iron", "Jade",
    "Keen", "Lunar", "Misty", "Noble", "Olive", "Proud", "Quiet", "Rapid", "Silver", "Tidal"];
string[] nouns = ["Harbor", "Falcon", "Meadow", "Summit", "Canyon", "River", "Forest", "Beacon", "Glacier", "Valley"];

// 200 two-word names, noun-major so neighbouring members share suffixes and lengths vary (9-13 chars): realistic
// collisions for any prefix- or length-based parser, and long enough to exercise multi-word packing.
var combos = nouns.SelectMany(noun => adjectives.Select(adjective => adjective + noun)).ToArray();
var large = combos[..199];
var medium = combos.Where((_, index) => index % 8 == 0).Take(24).ToArray();
string[] flagNames = ["Read", "Write", "Execute", "Delete", "Share", "Archive", "Audit", "Admin"];

const string header = """
    // <auto-generated>
    // Generated by ../generate_subjects.cs (run from benchmarks/: dotnet run generate_subjects.cs) - edit that, not this.
    // The BCL and Enums.NET work on any enum, so they use the FancyEnum ones. Enums NetEscapades.EnumGenerators is
    // compared on also get an identical copy prefixed "Ne", so no generator ever sees another's attributes and their
    // generated helper classes can't collide.
    // </auto-generated>
    #nullable enable
    using System;
    using System.ComponentModel;
    using FancyEnumGenerator.Attributes;
    using NetEscapades.EnumGenerators;

    namespace FancyEnumGenerator.Benchmarks;

    [FancyEnumMemberSet]
    [AttributeUsage(AttributeTargets.Field)]
    public sealed class StationInfoAttribute : Attribute
    {
        public string? Label { get; set; }
        public int Order { get; set; }
    }

    """;

const string unknown = "    Unknown = 0,\n";
Func<string, int, string> description = (name, _) => $"[Description(\"{Spaced(name)}\")] ";
// Order runs opposite to the numeric values, as a real display order independent of them would.
Func<string, int, string> stationInfo = (name, index) => $"[StationInfo(Label = \"{Spaced(name).Replace(' ', '-')}\", Order = {(medium.Length - index) * 10})] ";
var flags = "    None = 0,\n" + string.Join("\n", flagNames.Select((name, index) => $"    {name} = {1 << index},"));

var parts = new List<string> { header };
// Compared across all libraries: (name, FancyEnum attributes, body), each also emitted as Ne{name} for NetEscapades.
(string Name, string Fancy, string Body)[] shared =
[
    ("Medium", "[FancyEnum(CreateByteParsing = true, CreateTryFormat = true)]", unknown + Members(medium, description)),
    ("Large", "[FancyEnum]", unknown + Members(large)),
];
foreach (var (name, fancy, body) in shared)
{
    parts.Add(Enum(name, fancy, body));
    parts.Add(Enum("Ne" + name, "[EnumExtensions]", body));
}

// BCL vs FancyEnum only.
parts.Add(Enum("Sparse", "[FancyEnum(AllowNonContiguous = true)]", unknown + Members(medium, start: 3, step: 7)));
parts.Add(Enum("Permissions", "[Flags]\n[FancyEnum(AllowNoUnknown = true)]", flags));
// FancyEnum picks its ToString source per enum, so descriptions get their own copy of Medium; the BCL reads
// [Description] off Medium by reflection for the same comparison.
parts.Add(Enum("MediumDescribed", "[FancyEnum(DefaultToStringBehavior = FancyEnumDefaultToStringBehavior.DescriptionAttribute)]", unknown + Members(medium, description)));
// The same members with each of the other ValuesType options, for the enumeration benchmark (Medium uses the default, Span).
parts.Add(Enum("MediumInline", "[FancyEnum(ValuesType = FancyEnumValuesType.InlineArray)]", unknown + Members(medium)));
parts.Add(Enum("MediumCached", "[FancyEnum(ValuesType = FancyEnumValuesType.StaticCollection)]", unknown + Members(medium)));
// Custom per-member metadata: FancyEnum generates accessors; the BCL reads the attribute at runtime.
parts.Add(Enum("Station", "[FancyEnum]", unknown + Members(medium, stationInfo)));

var output = args.Length > 0 ? args[0] : Path.Combine("FancyEnumGenerator.Benchmarks", "Subjects.cs");
File.WriteAllText(output, string.Join("\n", parts));
Console.WriteLine($"Wrote {output}");

// AmberHarbor -> "amber harbor"
static string Spaced(string name) =>
    string.Concat(name.Select((character, index) => (char.IsUpper(character) && index > 0 ? " " : "") + char.ToLowerInvariant(character)));

static string Members(IReadOnlyList<string> names, Func<string, int, string>? attribute = null, int start = 1, int step = 1) =>
    string.Join("\n", names.Select((name, index) => $"    {attribute?.Invoke(name, index)}{name} = {start + index * step},"));

static string Enum(string name, string attributes, string body) => $"{attributes}\npublic enum {name}\n{{\n{body}\n}}\n";
