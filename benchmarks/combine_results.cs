// The repo's Directory.Build.props targets netstandard2.0 (for the library), which also applies to this script.
#:property TargetFramework=net10.0

// Builds docs/benchmarks.md from a BenchmarkDotNet run: a fixed introduction, then each class's *-report-github.md
// copied verbatim, so the published numbers are exactly what BenchmarkDotNet measured.
//
// Run from the repo root, after a benchmark run (see the "Running them" section below):
//   dotnet run benchmarks/combine_results.cs
//   dotnet run benchmarks/combine_results.cs -- path/to/BenchmarkDotNet.Artifacts/results
// With no argument it looks for results in the repo root, then in the benchmark project's folder.

var resultsDirectory = args.Length > 0
    ? args[0]
    : new[] { "BenchmarkDotNet.Artifacts/results", "benchmarks/FancyEnumGenerator.Benchmarks/BenchmarkDotNet.Artifacts/results" }.FirstOrDefault(Directory.Exists);
if (resultsDirectory is null || !Directory.Exists(resultsDirectory))
{
    Console.Error.WriteLine("No BenchmarkDotNet results found. Run the benchmarks first, or pass the results directory.");
    return 1;
}

// Report order and headings. Every class must be listed here, so a new benchmark class can't silently go missing.
(string Class, string Heading, string Description)[] sections =
[
    ("ToStringBenchmarks", "Formatting a member name",
        "`ToString()` and its equivalents, on a 25-member (Medium) and a 200-member (Large) enum, plus a value that isn't a declared member. For that one, the BCL formats the number (`\"999\"`), while FancyEnum returns `\"\"` by design."),
    ("ParseBenchmarks", "Parsing a member name",
        "Case-sensitive, for a member from the middle of the enum and for a plausible non-member (`Miss`)."),
    ("ParseIgnoreCaseBenchmarks", "Parsing, ignoring case",
        "An upper-cased member name, on the medium enum."),
    ("ParseUtf8Benchmarks", "Parsing UTF-8",
        "FancyEnum parses the bytes directly. The BCL has no byte overload, so its row transcodes into a stack buffer first, the cheapest route it allows."),
    ("MetadataBenchmarks", "Per-member metadata",
        "Formatting as, and parsing from, a `[Description]`, and reading a custom attribute's property. The BCL rows are the usual hand-rolled reflection (`GetField(...).GetCustomAttribute<T>()`)."),
    ("FlagsBenchmarks", "Flags",
        "Testing a flag, and formatting a combination that isn't a declared member. The output differs cosmetically: the BCL writes `Read, Write, Audit`, FancyEnum `Read|Write|Audit`."),
    ("IsDefinedBenchmarks", "Is a value declared?",
        "For a contiguous and a sparse enum. FancyEnum's check is `!IsUnknown`."),
    ("ValuesBenchmarks", "Enumerating every member",
        "Summing every member's value. FancyEnum's `Values`/`AsSpan` leave out `Unknown`, so they walk 24 members where the others walk 25. NetEscapades' `GetValues()` returns a new array per call, which .NET 10's JIT can stack-allocate here because the array never leaves the loop."),
    ("TryFormatBenchmarks", "Formatting into a buffer",
        "`TryFormat` into a caller-supplied `Span<char>`."),
];

var reports = Directory.GetFiles(resultsDirectory, "*-report-github.md")
    .ToDictionary(path => Path.GetFileName(path).Replace("FancyEnumGenerator.Benchmarks.", "").Replace("-report-github.md", ""));
var unlisted = reports.Keys.Except(sections.Select(section => section.Class)).ToArray();
if (unlisted.Length > 0)
{
    Console.Error.WriteLine($"Results for classes this script doesn't list: {string.Join(", ", unlisted)}. Add them to `sections`.");
    return 1;
}

var output = new System.Text.StringBuilder("""
    <!-- Generated by benchmarks/combine_results.cs from a BenchmarkDotNet run. Don't edit by hand: rerun it. -->
    # Benchmarks

    FancyEnum against the BCL (`System.Enum`), [NetEscapades.EnumGenerators](https://github.com/andrewlock/NetEscapades.EnumGenerators)
    (1.0.0-beta21) and [Enums.NET](https://github.com/TylerBrinkley/Enums.NET) (5.0.0). Source: [`benchmarks/`](../benchmarks).
    The tables below are BenchmarkDotNet's own reports, unedited.

    - **Which libraries appear where:** all four are compared on formatting and parsing names, which each supports
      natively. Everything else is BCL vs FancyEnum, plus any library with a native API for it; nothing gets a shim
      (such as a UTF-8 transcode) just to fill in a row.
    - **Fairness:** every benchmark checks during setup that all the libraries in it produce the same answer for its
      input, so no row measures different work than another.
    - **Enums:** *Medium* has 25 members and *Large* has 200, with two-word names 9 to 13 characters long, many sharing
      prefixes and lengths ([`generate_subjects.cs`](../benchmarks/generate_subjects.cs)).
    - **Reading the tables:** results under about 1 ns are at the measurement floor, effectively a constant load. `Ratio`
      is relative to the BCL row in the same group. `-` under `Allocated` means nothing was allocated.


    """);

foreach (var (className, heading, description) in sections)
{
    if (!reports.TryGetValue(className, out var path))
    {
        Console.Error.WriteLine($"Warning: no results for {className}; leaving it out.");
        continue;
    }
    output.Append($"## {heading}\n\n{description}\n\n");
    output.Append(File.ReadAllText(path).Trim());
    output.Append("\n\n");
}

output.Append("""
    ## Running them

    ```bash
    # Full precision (roughly 20 to 25 minutes), then regenerate this page:
    dotnet run -c Release --project benchmarks/FancyEnumGenerator.Benchmarks -- --filter "*"
    dotnet run benchmarks/combine_results.cs

    # A quick look (roughly 10 minutes; wider error bars):
    dotnet run -c Release --project benchmarks/FancyEnumGenerator.Benchmarks -- --filter "*" --job short
    ```

    """);

var docPath = Path.Combine("docs", "benchmarks.md");
File.WriteAllText(docPath, output.ToString());
Console.WriteLine($"Wrote {docPath} from {reports.Count} reports in {resultsDirectory}.");
return 0;
